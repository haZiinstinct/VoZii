_LANG = "de"


def set_language(lang: str) -> None:
    global _LANG
    _LANG = lang if lang in STRINGS else "de"


def get_language() -> str:
    return _LANG


def is_rtl() -> bool:
    return _LANG in RTL_LANGS


def t(key: str, **kwargs) -> str:
    """Uebersetzt key in die aktive Sprache. Fallback: aktiv -> en -> de -> key."""
    for lang in (_LANG, "en", "de"):
        table = STRINGS.get(lang)
        if table and key in table:
            text = table[key]
            return text.format(**kwargs) if kwargs else text
    return key


def detect_system_language() -> str:
    """Windows-UI-Sprache -> eine der UI_LANGUAGES, sonst 'en'.

    Englisch als weltweiter Default — ein italienisches/polnisches Windows
    soll keine deutsche Oberflaeche bekommen."""
    try:
        import ctypes
        lcid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        primary = lcid & 0x3FF  # primaere Sprach-ID
        mapping = {
            0x07: "de", 0x09: "en", 0x0A: "es", 0x0C: "fr", 0x16: "pt",
            0x19: "ru", 0x04: "zh", 0x11: "ja", 0x01: "ar",
        }
        return mapping.get(primary, "en")
    except Exception:
        return "en"


